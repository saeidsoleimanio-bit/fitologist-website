/* ---------------------------------------------------------- BlendedImage */

type Fade = { t?: string; r?: string; b?: string; l?: string };

/**
 * Frameless photograph that dissolves into the section background
 * (CSS mask via `.blend-edges`), with a subtle 1.03 → 1 entrance and gentle
 * parallax. The masked edges also hide any parallax travel, so no overscan crop.
 */
export function BlendedImage({
  src,
  alt,
  sizes,
  className = "",
  imgClassName = "object-cover",
  fade,
  strength = 3,
  quality = 85,
  mask,
}: {
  src: string;
  alt: string;
  sizes: string;
  className?: string;
  imgClassName?: string;
  fade?: Fade;
  /** Custom mask-image (e.g. a radial vignette) replacing the default edge fade */
  mask?: string;
  /** percentage of vertical parallax travel */
  strength?: number;
  quality?: number;
}) {
  const ref = useRef<HTMLDivElement>(null);
  const reduce = useReducedMotion();
  const { scrollYProgress } = useScroll({ target: ref, offset: ["start end", "end start"] });
  const y = useTransform(scrollYProgress, [0, 1], [`-${strength}%`, `${strength}%`]);
  const fadeVars = {
    ...(fade?.t && { "--fade-t": fade.t }),
    ...(fade?.r && { "--fade-r": fade.r }),
    ...(fade?.b && { "--fade-b": fade.b }),
    ...(fade?.l && { "--fade-l": fade.l }),
    ...(mask && { maskImage: mask, WebkitMaskImage: mask }),
  } as React.CSSProperties;

  return (
    <div ref={ref} className={`blend-edges relative ${className}`} style={fadeVars}>
      <motion.div className="absolute inset-0" style={reduce ? undefined : { y }}>
        <motion.div
          className="absolute inset-0"
          initial={{ scale: 1.03 }}
          whileInView={{ scale: 1 }}
          viewport={{ once: true, amount: 0.2 }}
          transition={{ duration: 1.6, ease: EASE }}
        >
          <Image src={src} alt={alt} fill sizes={sizes} quality={quality} className={imgClassName} />
        </motion.div>
      </motion.div>
    </div>
  );
}

/* --------------------------------------------------------- LogoWatermark */

/**
 * The FITologist mark as a barely-visible background element (≈3% opacity).
 * Uses the transparent crop generated by scripts/optimize-images.mjs.
 */
export function LogoWatermark({
  className = "",
  opacity = 0.03,
  travel = 18,
}: {
  className?: string;
  opacity?: number;
  travel?: number;
}) {
  const ref = useRef<HTMLDivElement>(null);
  const reduce = useReducedMotion();
  const { scrollYProgress } = useScroll({ target: ref, offset: ["start end", "end start"] });
  const y = useTransform(scrollYProgress, [0, 1], [`${travel}%`, `-${travel}%`]);

  return (
    <div
      ref={ref}
      aria-hidden
      className="pointer-events-none absolute inset-0 overflow-hidden select-none"
    >
      <motion.div
        className={`absolute ${className}`}
        style={reduce ? { opacity } : { y, opacity }}
      >
        <Image
          src="/images/logo-mark.png"
          alt=""
          width={606}
          height={474}
          sizes="(min-width: 1024px) 60vw, 110vw"
          className="h-auto w-full"
        />
      </motion.div>
    </div>
  );
}
