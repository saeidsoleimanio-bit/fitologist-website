"use client";

import { motion, useReducedMotion, useScroll, useTransform } from "framer-motion";
import Image from "next/image";
import { useRef } from "react";
import { EASE, fadeUp, VIEWPORT } from "@/lib/motion";

/* ---------------------------------------------------------------- Reveal */

export function Reveal({
  children,
  className,
  delay = 0,
  as = "div",
}: {
  children: React.ReactNode;
  className?: string;
  delay?: number;
  as?: "div" | "li" | "p" | "span";
}) {
  const Comp = motion[as];
  return (
    <Comp
      className={className}
      initial="hidden"
      whileInView="show"
      viewport={VIEWPORT}
      variants={fadeUp}
      custom={delay}
    >
      {children}
    </Comp>
  );
}

/* ------------------------------------------------------------ AccentLine */

export function AccentLine({
  className = "",
  delay = 0,
  origin = "start",
}: {
  className?: string;
  delay?: number;
  origin?: "start" | "end" | "center";
}) {
  // Logical origin: grows from the reading start (right edge in RTL).
  const originCls = origin === "center" ? "origin-center" : origin === "end" ? "origin-right rtl:origin-left" : "origin-left rtl:origin-right";
  return (
    <motion.span
      aria-hidden
      className={`block h-px bg-ember ${originCls} ${className}`}
      initial={{ scaleX: 0 }}
      whileInView={{ scaleX: 1 }}
      viewport={{ once: true, amount: 0.8 }}
      transition={{ duration: 1.1, ease: EASE, delay }}
    />
  );
}

/* -------------------------------------------------------- SectionHeading */

export function SectionHeading({
  index,
  label,
  title,
  id,
  className = "",
  align = "left",
}: {
  index?: string;
  label: string;
  title: React.ReactNode;
  id?: string;
  className?: string;
  align?: "left" | "center";
}) {
  const centered = align === "center";
  return (
    <div className={`${centered ? "text-center" : ""} ${className}`}>
      <Reveal
        className={`eyebrow flex items-center gap-4 ${centered ? "justify-center" : ""}`}
      >
        {index && <span className="text-ember">{index}</span>}
        <AccentLine className="w-10" />
        <span>{label}</span>
      </Reveal>
      <Reveal delay={0.08}>
        <h2
          id={id}
          className="display mt-4 text-[clamp(2.25rem,7.4vw,4.4rem)] text-bone text-balance"
        >
          {title}
        </h2>
      </Reveal>
    </div>
  );
}

